// The one-page poster, hand-drawn.
//
// Thirty-five posts and four projects on one canvas, in eight panels: the
// forward pass in order, the four object kinds and the contract they share,
// the three gradients, the optimiser lineage, the training loop in its two
// lanes, the ways training fails, what closes the train-test gap, and the
// numerical floor underneath all of it.
//
// The sheet is laid out on the same 1200 x 1700 grid as the Context
// Engineering series' poster, so the two hang together: two 530-wide columns,
// a full-width lane at panel five, and another at panel eight. At 1200 by 1700
// it sits three pixels off the A-series ratio, which is to say it prints at A2
// without a crop worth noticing.
//
// Every number on the sheet is measured, not quoted. The optimiser and
// regularisation figures come from verify/RESULTS.md and the project figures
// from verify/projects_results.md, both regenerated by running the series' own
// classes under nnfs.init() (seed 0). Where a post's prose and the measured
// value disagree, the measured value is the one printed here.
//
// Coordinates below are text BASELINES, the way a typeset sheet's own source
// reads. tb() converts a baseline into the top-left origin an Excalidraw text
// element wants, so every number here can be checked against a rendered line.

const fs = require('fs');
const { T, rect, text, line, arrow, resetSeq } = require('./lib');
const { emit, fit, rule } = require('./scaffold');

const W = 1200, H = 1700;

// Type scale. The panel heads run at 20 and the body at 13, one notch under the
// per-post figures, because a poster holds four times as much text in the same
// column and Excalifont runs wide.
const SZ = { title: 40, sub: 16, head: 20, label: 15, small: 13, tiny: 11, mono: 12.5 };

const MONO = 3;                                   // fontFamily 3 = JetBrains Mono

// Baseline -> element origin. The renderer puts the baseline at y + size*0.92.
const tb = (x, baseline, str, o = {}) =>
  text(x, baseline - (o.size ?? SZ.small) * 0.92, str, o);

const small = (x, y, s, o = {}) => tb(x, y, s, { size: SZ.small, stroke: T.inkMuted, ...o });
const tiny = (x, y, s, o = {}) => tb(x, y, s, { size: SZ.tiny, stroke: T.inkSubtle, ...o });
const label = (x, y, s, o = {}) => tb(x, y, s, { size: SZ.label, stroke: T.ink, ...o });
const mono = (x, y, s, o = {}) => tb(x, y, s, { size: SZ.mono, stroke: T.ink, family: MONO, ...o });
const head = (x, y, s) => tb(x, y, s, { size: SZ.head, stroke: T.ink });

// A panel is a calm container, so it gets less wobble than the things inside it.
const panel = (x, y, w, h) =>
  rect(x, y, w, h, { stroke: T.border, fill: T.surface, strokeWidth: 1, roughness: 0.7 });

const box = (x, y, w, h, o = {}) =>
  rect(x, y, w, h, { stroke: T.ink, fill: T.surface, strokeWidth: 1.2, roughness: 1, ...o });

// A numeral badge on a saturated fill. Every fill in this palette reads better
// under dark ink than under on-fill: against --ce-primary, the lightest of the
// four, dark ink measures 4.34:1 and on-fill 3.95. The numerals are set at 20,
// which is large text, so 4.34 clears the 3:1 bar with room to spare.
//
// Numerals rather than initials: the four object kinds are Layer, Activation,
// Loss and Optimiser, and L for two of them would be worse than no letter.
const badge = (x, y, fill, glyph) => [
  rect(x, y, 30, 30, { stroke: T.ink, fill, strokeWidth: 1.4 }),
  tb(x, y + 21, glyph, { size: 20, align: 'center', width: 30, stroke: T.onAccent }),
];

// One stage of a pipeline: a name and two lines of gloss in a plain box.
const stage = (x, y, w, h, name, d1, d2) => [
  box(x, y, w, h),
  tb(x + 12, y + 19, fit(name, SZ.small, w - 24, `stage ${name}`), { size: SZ.small, stroke: T.ink }),
  tb(x + 12, y + 34, fit(d1, SZ.tiny, w - 24, `stage ${name} d1`), { size: SZ.tiny, stroke: T.inkMuted }),
  tb(x + 12, y + 47, fit(d2, SZ.tiny, w - 24, `stage ${name} d2`), { size: SZ.tiny, stroke: T.inkMuted }),
];

const flow = (x1, x2, y) => arrow([[x1, y], [x2, y]], { stroke: T.inkMuted, strokeWidth: 1.3 });

// ---------------------------------------------------------------------------
function poster() {
  resetSeq();
  const e = [];

  // ------------------------------------------------------------- header
  e.push(tb(60, 82, 'One page of neural networks from scratch', { size: SZ.title, stroke: T.ink }));
  e.push(small(60, 112,
    'Everything the network computes on one pass, and everything that changes it on the way back.',
    { size: SZ.sub }));
  e.push(rule(60, 1140, 134));

  // ------------------------------------------------------ 1 · forward pass
  e.push(panel(60, 156, 530, 306));
  e.push(head(82, 188, '1 · The forward pass, in order'));
  e.push(small(82, 208, fit('Inner dimensions match, outer survive: (m,n)·(n,p) → (m,p).', SZ.small, 486, 'p1 sub')));

  // Name, output shape, and what produced it. The shape column is the reason
  // the panel is a table rather than a chain of arrows: it is the thing a
  // reader checks their own code against.
  const FWD = [
    ['01', 'X · input batch', '(N, 2)', 'spiral_data(samples=100, classes=3)'],
    ['02', 'dense1 · Dense', '(N, 3)', 'Z₁ = X · W₁ + b₁,  W₁ is (2, 3)'],
    ['03', 'Activation_ReLU', '(N, 3)', 'A₁ = np.maximum(0, Z₁), elementwise'],
    ['04', 'dense2 · Dense', '(N, 3)', 'Z₂ = A₁ · W₂ + b₂, the logits'],
    ['05', 'Activation_Softmax', '(N, 3)', 'exp(Z₂ − rowmax) / Σ, rows sum to 1'],
    ['06', 'Loss · calculate()', 'scalar', '−log ŷ at the true class, meaned'],
  ];
  FWD.forEach(([n, name, shape, formula], i) => {
    const y = 214 + i * 35;
    // The loss is the only row that leaves the batch dimension behind, so it is
    // the only one with a spine. Anything more and the stack reads as six colours.
    e.push(box(82, y, 486, 31, { stroke: i === 5 ? T.accent : T.border, strokeWidth: i === 5 ? 1.6 : 1 }));
    e.push(mono(94, y + 21, n, { size: 12, stroke: T.inkSubtle }));
    e.push(tb(120, y + 21, fit(name, SZ.small, 140, 'fwd name'), { size: SZ.small, stroke: T.ink }));
    e.push(mono(266, y + 21, fit(shape, 12, 58, 'fwd shape'), { size: 12, stroke: T.primary }));
    e.push(tb(330, y + 21, fit(formula, 11, 228, 'fwd formula'), { size: 11, stroke: T.inkMuted }));
  });
  e.push(small(82, 448, fit('Without a ReLU between them, two Dense layers collapse into one.', 12, 486, 'p1 note'),
    { size: 12 }));

  // -------------------------------------------------------- 2 · the contract
  e.push(panel(610, 156, 530, 306));
  e.push(head(632, 188, '2 · Four objects, one contract'));
  e.push(small(632, 208, fit('One of four kinds, plus two that fuse an activation and a loss.', 12, 486, 'p2 sub'),
    { size: 12 }));

  const KINDS = [
    ['1', T.primary, 'Layer', 'forward(inputs) · backward(dvalues)',
      'Layer_Dense owns weights, biases, and their gradients'],
    ['2', T.accent, 'Activation', 'forward(inputs) · backward(dvalues)',
      'Activation_ReLU: no parameters; inputs, output, dinputs'],
    ['3', T.warn, 'Loss', 'forward(y_pred, y_true) → per-sample losses',
      'the base class adds calculate() and regularization_loss()'],
    ['4', T.success, 'Optimiser', 'pre · update_params(layer) · post_update_params',
      'Optimizer_Adam keeps its buffers on the layer, not on itself'],
  ];
  KINDS.forEach(([g, fill, name, contract, state], i) => {
    const y = 218 + i * 50;
    e.push(...badge(632, y, fill, g));
    e.push(label(674, y + 15, name));
    e.push(mono(674, y + 31, fit(contract, 11, 444, 'contract'), { size: 11, stroke: T.inkMuted }));
    e.push(tb(674, y + 45, fit(state, 11, 444, 'state'), { size: 11, stroke: T.inkSubtle }));
  });
  e.push(small(632, 436, fit('Swap the Loss and it regresses: project 04, Loss_MSE, no activation.', 12, 486, 'p2 n1'),
    { size: 12, stroke: T.ink }));
  e.push(small(632, 454, fit('A conv layer is still a forward and a backward; AdamW, three hooks.', 12, 486, 'p2 n2'),
    { size: 12 }));

  // ----------------------------------------------------------- 3 · backprop
  e.push(panel(60, 482, 530, 300));
  e.push(head(82, 514, '3 · Backprop, the three gradients'));
  e.push(small(82, 534, fit('Random search moved the loss 1.099 → 1.095 in 100 000 draws.', SZ.small, 486, 'p3 sub')));

  const GRADS = [
    ['Chain rule', 'dL/dW₁ = dL/dZ₂ · dZ₂/dA₁ · dA₁/dZ₁ · dZ₁/dW₁',
      'one local derivative per function, multiplied'],
    ['dweights', 'np.dot(self.inputs.T, dvalues)',
      '(n_in, n_out) — upstream gradient × input'],
    ['dbiases', 'np.sum(dvalues, axis=0, keepdims=True)',
      '(1, n_out) — the bias input is always 1'],
    ['dinputs', 'np.dot(dvalues, self.weights.T)',
      '(N, n_in) — sums the n_out paths each input feeds'],
    ['Softmax + CCE', 'dL/dZ = (ŷ − y) / N',
      '(N, C) — O(N·C) work, not the O(N·C²) Jacobian'],
    ['Sigmoid + BCE', 'dL/dz = (σ(z) − y) / N',
      '(N, 1) — ŷ(1−ŷ) cancels, so no tiny division'],
  ];
  GRADS.forEach(([name, formula, note], i) => {
    const y = 548 + i * 34;
    e.push(tb(82, y + 12, fit(name, SZ.small, 114, 'grad name'), { size: SZ.small, stroke: T.ink }));
    e.push(mono(200, y + 12, fit(formula, 12, 368, 'grad formula'), { size: 12, stroke: T.ink }));
    e.push(tb(200, y + 27, fit(note, 11, 368, 'grad note'), { size: 11, stroke: T.inkMuted }));
  });
  e.push(small(82, 770, fit('Every backward is the chain rule. The fused tail is (ŷ − y)/N.', 12, 486, 'p3 note'),
    { size: 12 }));

  // --------------------------------------------------------- 4 · optimisers
  e.push(panel(610, 482, 530, 300));
  e.push(head(632, 514, '4 · Six optimisers, one lineage'));
  e.push(small(632, 534, fit('One shared run: seed 0, spiral 300, 2→64→3, 10 001 epochs.', SZ.small, 486, 'p4 sub')));

  e.push(tiny(790, 556, 'UPDATE RULE'));
  e.push(tiny(1010, 556, 'ACC', { align: 'right', width: 54 }));
  e.push(tiny(1064, 556, 'LOSS', { align: 'right', width: 54 }));

  const OPT = [
    ['Optimizer_SGD', 'α = 1.0', 'θ −= α·g', '64.7%', '0.87', T.inkMuted],
    ['+ decay', 'd = 1e-3', 'α(t) = α₀ / (1 + d·t)', '64.7%', '0.76', T.inkMuted],
    ['+ momentum', 'β = 0.9', 'v = βv − α·g ;  θ += v', '95.7%', '0.12', T.success],
    ['Optimizer_Adagrad', 'ε = 1e-7', 'G += g² ;  θ −= α·g/(√G + ε)', '84.0%', '0.38', T.inkMuted],
    ['Optimizer_RMSprop', 'ρ = 0.999', 'G = ρG + (1−ρ)g²', '90.0%', '0.24', T.inkMuted],
    ['Optimizer_Adam', 'β₁ .9  β₂ .999', 'θ −= α·m̂/(√v̂ + ε)', '96.3%', '0.08', T.success],
  ];
  OPT.forEach(([name, knob, ruleText, acc, loss, tint], i) => {
    const y = 570 + i * 30;
    e.push(tb(632, y, fit(name, SZ.small, 152, 'opt name'), { size: SZ.small, stroke: T.ink }));
    e.push(tb(632, y + 14, fit(knob, 10, 152, 'opt knob'), { size: 10, stroke: T.inkSubtle }));
    e.push(mono(790, y + 4, fit(ruleText, 12, 214, 'opt rule'), { size: 12, stroke: T.ink }));
    e.push(mono(1010, y + 4, acc, { size: 12, stroke: tint, align: 'right', width: 54 }));
    e.push(mono(1064, y + 4, loss, { size: 12, stroke: tint, align: 'right', width: 54 }));
  });

  e.push(rule(632, 1118, 744));
  e.push(small(632, 760, fit('Adam defaults lr=0.001, decay=0, ε=1e-7, β₁=.9, β₂=.999; Part 27 runs .02.',
    SZ.tiny, 486, 'p4 n1'), { size: SZ.tiny }));
  e.push(small(632, 776, fit('Vanilla SGD is slow, not stuck: 64.7% at 10k epochs, 90.7% at 50k.',
    SZ.tiny, 486, 'p4 n2'), { size: SZ.tiny }));

  // ------------------------------------------------------ 5 · training loop
  e.push(panel(60, 802, 1080, 300));
  e.push(head(82, 834, '5 · The training loop, end to end'));
  e.push(small(82, 856, fit(
    'One step in two lanes. Lane B differs from lane A only by subtraction: no dropout, no regularisation loss, no backward, no update.',
    SZ.small, 1036, 'p5 sub')));

  e.push(tiny(82, 886, 'LANE A · TRAINING STEP · READS AND WRITES THE WEIGHTS'));
  const TRAIN = [
    ['0 Scale', 'fit mean/std on the', 'training fold only'],
    ['1 Batch', 'shuffle, slice B=128', '469 steps on MNIST'],
    ['2 Forward', 'dropout is on', 'dense1 → … → softmax'],
    ['3 Loss + tally', 'data_loss + reg_loss', 'argmax == y, running'],
    ['4 Backward', 'loss_act.backward()', '… → dense1.backward'],
    ['5 Update', 'pre → update → post', 'once per layer'],
  ];
  TRAIN.forEach(([n, d1, d2], i) => {
    const x = 82 + i * 173;
    e.push(...stage(x, 894, 152, 52, n, d1, d2));
    if (i) e.push(flow(x - 21, x - 4, 920));
  });

  e.push(tiny(82, 976, 'LANE B · EVALUATION · READS THEM AND NOTHING ELSE'));
  const EVAL = [
    ['0 Scale', 'apply the stored stats', 'never refit on test'],
    ['1 Forward', 'training=False throughout', 'dropout is identity'],
    ['2 Loss', 'data loss only', 'no regularisation term'],
    ['3 Argmax', 'np.argmax(output, axis=1)', 'one label per row'],
    ['4 Score', 'np.mean(pred == y)', 'the test set opens once'],
  ];
  EVAL.forEach(([n, d1, d2], i) => {
    const x = 82 + i * 208;
    e.push(...stage(x, 984, 186, 52, n, d1, d2));
    if (i) e.push(flow(x - 22, x - 4, 1010));
  });

  e.push(small(82, 1060, fit(
    'Split 60–80 / 10–20 / 10–20. Tune on validation, refit, then open the test set once. k = 5 folds, each scaler refitted inside its fold.',
    SZ.small, 1036, 'p5 n1')));
  e.push(small(82, 1082, fit(
    'B = 128 over 60 000 MNIST samples is 469 updates an epoch, 9 380 over twenty. Shuffle every epoch, and decay now applies per step.',
    SZ.small, 1036, 'p5 n2'), { stroke: T.ink }));

  // ------------------------------------------------------------ 6 · failures
  e.push(panel(60, 1122, 530, 268));
  e.push(head(82, 1154, '6 · Six ways training fails'));
  e.push(small(82, 1174, fit('The symptom as it appears, then the first thing to change.', 12, 486, 'p6 sub'),
    { size: 12 }));

  const FAIL = [
    ['Dead ReLU', 'gradients all zero; the unit outputs 0 for any input',
      'He init sqrt(2/n_in), and lower the rate'],
    ['Vanishing init', 'loss flat at ln(C); variance ÷150 per layer at n=64',
      'np.sqrt(2.0/n_inputs) replaces 0.01*randn'],
    ['Overfitting', 'train 95.3%, test 78.7% — a 16.6-point gap',
      'L2 5e-4 on dense1: test 84.0%, gap 11.3'],
    ['AdaGrad stall', 'the rate decays to zero and training stalls for good',
      "RMSProp's decaying cache instead"],
    ['Adam rebuilt', 'Adam quietly degrades to plain SGD',
      'build it once, outside both loops'],
    ['Dropout at eval', 'test accuracy wanders from run to run',
      'forward(x, training=False) at evaluation'],
  ];
  FAIL.forEach(([name, symptom, fixIt], i) => {
    const y = 1184 + i * 33;
    e.push(tb(82, y + 12, fit(name, SZ.small, 114, 'fail name'), { size: SZ.small, stroke: T.ink }));
    e.push(tb(200, y + 12, fit(symptom, 11, 368, 'fail symptom'), { size: 11, stroke: T.inkMuted }));
    e.push(tb(200, y + 27, fit(`first fix — ${fixIt}`, 11, 368, 'fail fix'), { size: 11, stroke: T.success }));
  });

  // ------------------------------------------------------ 7 · generalisation
  e.push(panel(610, 1122, 530, 268));
  e.push(head(632, 1154, '7 · Closing the train-test gap'));
  e.push(small(632, 1174, fit('The gap is the diagnosis. Figures below: 100 samples per class.', 12, 486, 'p7 sub'),
    { size: 12 }));

  const GEN = [
    ['Underfitting', 'train low, test low, and a small gap',
      'more neurons, more layers, more epochs'],
    ['Good fit', 'train high, test high, and a small gap',
      'ship it, then watch for distribution shift'],
    ['Overfitting', 'train 95.3%, test 78.7%, gap 16.6 points',
      'validation loss flattens, then climbs'],
    ['L2 · λ=5e-4', 'loss += λΣw² ;  grad += 2λw',
      'test 78.7% → 84.0%; the gap 16.6 → 11.3'],
    ['L1 · λ=5e-4', 'loss += λΣ|w| ;  grad += λ·sign(w)',
      'sparse; test 80.3%. L1+L2 gives the smallest gap, 1.7'],
    ['Dropout(0.1)', 'mask ~ binomial(1, 1−p) / (1−p), per step',
      'over-regularises this 64-neuron net: test 64.7%'],
  ];
  GEN.forEach(([name, what, result], i) => {
    const y = 1184 + i * 33;
    e.push(tb(632, y + 12, fit(name, SZ.small, 114, 'gen name'), { size: SZ.small, stroke: T.ink }));
    e.push(tb(750, y + 12, fit(what, 11, 368, 'gen what'), { size: 11, stroke: T.inkMuted }));
    e.push(tb(750, y + 27, fit(result, 11, 368, 'gen result'), { size: 11, stroke: T.primary }));
  });

  // --------------------------------------------------------------- 8 · floor
  e.push(panel(60, 1410, 1080, 212));
  e.push(head(82, 1442, '8 · The numerical floor, and what to check before trusting a run'));
  e.push(small(82, 1462, fit(
    'Only the last rule on the left raises anything. The other four just make the numbers quietly wrong.',
    12, 1036, 'p8 sub'), { size: 12 }));

  e.push(tiny(82, 1482, 'THE FLOOR'));
  e.push(tiny(640, 1482, 'BEFORE YOU TRUST A RUN'));

  [
    '1 · Subtract the per-row max before np.exp, or e¹⁰⁰⁰ = inf.',
    '2 · np.clip(y_pred, 1e-7, 1 − 1e-7) before taking any log.',
    '3 · Split the sigmoid on the sign of z; np.exp overflows past 700.',
    '4 · keepdims=True on every reduction, or (N,) broadcasts as a row.',
    '5 · nnfs.init() patches np.dot; a plain Python list raises.',
  ].forEach((s, i) => e.push(small(82, 1504 + i * 24, fit(s, SZ.small, 518, 'floor rule'))));

  [
    'Gradient-check: centred difference h=1e-5, rel. error < 1e-5.',
    'Iteration-0 loss ≈ ln(C): 0.69, 1.10, 2.30 at C = 2, 3, 10.',
    'assert dweights.shape == weights.shape, on every layer.',
    'Overfit one tiny batch first; scale up once it reaches 100%.',
    'Post-ReLU zero fraction near 0.5, activation std near 1.',
  ].forEach((s, i) => e.push(small(640, 1504 + i * 24, fit(s, SZ.small, 478, 'check'))));

  // ------------------------------------------------------------- footer
  e.push(rule(60, 1140, 1642));
  e.push(small(60, 1664, fit(
    'Four projects, run end to end — MNIST 98.0% · two-moons 100% · Fashion-MNIST 87.1% · California housing R² 0.823, RMSE $49.2k.',
    SZ.small, 1080, 'footer projects'), { stroke: T.ink }));
  e.push(small(60, 1686, fit(
    'Neural Networks from Scratch — 35 posts, 4 projects, NumPy only. Every figure here is measured under nnfs.init() seed 0, not assumed.',
    SZ.small, 1080, 'footer series')));

  return {
    W, H, els: e,
    title: 'One page of neural networks from scratch, drawn by hand',
    desc: 'A hand-drawn single-sheet reference for the Neural Networks from Scratch series, laid out '
      + 'in eight panels. Panel one tables the forward pass in order, giving each stage its output '
      + 'shape for a batch of N samples: the input batch at N by 2, a Dense layer to N by 3, ReLU '
      + 'unchanged at N by 3, a second Dense layer producing logits, softmax producing rows that sum '
      + 'to one, and the loss collapsing to a scalar; it is headed by the rule that inner dimensions '
      + 'match and outer dimensions survive, and closes by noting that without a ReLU between them '
      + 'two Dense layers collapse into one. Panel two gives the four object kinds — Layer, '
      + 'Activation, Loss and Optimiser — each with its method contract and the state it owns, '
      + 'noting that two further classes fuse an activation with a loss, that swapping only the Loss '
      + 'turns the same stack into a regressor, and that a convolutional layer is still a forward '
      + 'and a backward while AdamW is still the same three optimiser hooks. Panel three gives the '
      + 'three gradients a Dense layer computes — dweights as the input transpose dotted with the '
      + 'upstream gradient, dbiases as a keepdims sum over the batch, dinputs as the upstream '
      + 'gradient dotted with the weight transpose — each with its shape, above the two fused '
      + 'backward passes, softmax with cross-entropy and sigmoid with binary cross-entropy, which '
      + 'both collapse to predictions minus targets over N; its subtitle records that random search '
      + 'moved the loss only from 1.099 to 1.095 in a hundred thousand draws, which is why gradients '
      + 'exist. Panel four lists six optimisers in the order the series builds them, each with its '
      + 'update rule, its characteristic hyperparameter and its measured accuracy and loss on one '
      + 'shared spiral run: SGD at 64.7 per cent and 0.87, decay at 64.7 and 0.76, momentum at 95.7 '
      + 'and 0.12, AdaGrad at 84.0 and 0.38, RMSProp at 90.0 and 0.24, and Adam at 96.3 and 0.08; it '
      + 'notes Adam\'s class defaults and that vanilla SGD is slow rather than stuck, reaching 90.7 '
      + 'per cent by fifty thousand epochs. Panel five runs the training loop in two lanes: lane A, '
      + 'the training step, scales inputs, batches, runs the forward pass with dropout on, computes '
      + 'the data and regularisation loss with a running accuracy tally, runs the backward pass and '
      + 'then the three optimiser hooks; lane B, evaluation, applies the stored scaling, runs '
      + 'forward with training set to false, takes the data loss only, takes an argmax and scores, '
      + 'differing from lane A only by subtraction. Panel six lists six ways training fails with '
      + 'each symptom and its first fix: dead ReLU, vanishing initialisation, overfitting, the '
      + 'AdaGrad stall, an optimiser rebuilt inside the loop, and dropout left on at evaluation. '
      + 'Panel seven reads the train-test gap, from underfitting through a good fit to overfitting, '
      + 'then gives L2, L1 and dropout with their measured effect on test accuracy. Panel eight sets '
      + 'five numerical-floor rules — subtract the row max before exponentiating, clip before taking '
      + 'a log, split the sigmoid on the sign of z, keep dimensions on every reduction, and the '
      + 'np.dot patch nnfs.init() installs — against five checks to run before trusting a training '
      + 'run, and observes that only the last rule raises anything while the rest fail silently. A '
      + 'footer records the four projects as run end to end: MNIST at 98.0 per cent, two-moons at '
      + '100, Fashion-MNIST at 87.1, and California housing at an R squared of 0.823. Same '
      + 'eight-panel rhythm as the Context Engineering poster, so the two can be read side by side.',
  };
}

module.exports = { poster, W, H };

if (require.main === module) {
  const dir = process.argv[2];
  if (!dir) {
    console.error('usage: node poster.js <output-directory>');
    process.exit(2);
  }
  fs.mkdirSync(dir, { recursive: true });
  emit('one-page-of-neural-networks-from-scratch', poster());
}
